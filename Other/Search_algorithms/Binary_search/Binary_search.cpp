#include <iostream>
#include <algorithm>

using namespace std;

int main()
{
    setlocale(LC_ALL, "Rus");

    const int SIZE = 10; // Размер массива
    int arr[SIZE];       // Создаем массив из 10 элементов
    int key;             // Переменная для хранения ключа

    cout << "Введите " << SIZE << " чисел для заполнения массива: " << endl;

    for (int i = 0; i < SIZE; i++)
    {
        cin >> arr[i];
    }

    sort(arr, arr + SIZE); // Сортируем массив

    cout << "\nОтсортированный массив: ";
    for (int i = 0; i < SIZE; i++)
    {
        cout << arr[i] << " ";
    }

    cout << "\n\nВведите ключ: ";
    cin >> key;

    int left = 0, right = SIZE - 1;
    bool found = false;
    int mid;

    while (left <= right)
    {
        mid = left + (right - left) / 2; // Избегаем возможного переполнения (лучше, чем (left + rigth) / 2)

        if (arr[mid] == key)
        {
            found = true;
            break;
        }

        if (arr[mid] > key)
        {
            right = mid - 1; // Поиск в левой части
        }
        else
        {
            left = mid + 1; // Поиск в правой части
        }
    }

    if (found)
    {
        cout << "Элемент " << key << " найден в индексе: " << mid << endl;
    }
    else
    {
        cout << "Элемент" << key << " не найден в массиве" << endl;
    }

    return 0;
}