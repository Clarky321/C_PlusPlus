/*
ПРИМЕР ЛИНЕЙНОГО ПОИСКА #_2.
*/
#include <iostream>
#include <cstdlib>
#include <ctime>

using namespace std;

int main()
{
	setlocale(LC_ALL, "Rus");

	srand(time(NULL));		// Инициализация генератора случайных чисел

	const int SIZE = 50;	// Размер массива
	int arr[SIZE];			// Массив на 20 элементов
	int key;				// Переменная для хранения искомого ключа
	int foundIndices[SIZE]; // Массив для хранения индексов найденных элементов
	int foundCount = 0;		// Количество найденных совпадений

	// Заполнение массива случайными числами и его вывод
	cout << "Сгенерированный массив:\n";

	for (int i = 0; i < SIZE; i++)
	{
		arr[i] = 1 + rand() % 20; // Заполнение случайными числами от 1 до 20
		cout << arr[i] << " ";

		if (i == 9) cout << endl; // Разделяем вывод для удобства чтения
	}

	// Ввод ключа
	cout << "\n\nВведите ключ: ";
	cin >> key;

	// Линейный поиск ключа в массиве
	for (int i = 0; i < SIZE; i++)
	{
		if (arr[i] == key)
		{
			foundIndices[foundCount++] = i; // Запоминаем индекс найденного элемента
		}
	}

	// Вывод результатов
	if (foundCount > 0)
	{
		cout << "Ключ " << key << " найден в индексах: ";

		for (int i = 0; i < foundCount; i++)
		{
			cout << foundIndices[i] << " ";
		}
		cout << endl;
	}
	else
	{
		cout << "Ключ " << key << " не найден в массиве." << endl;
	}

	return 0;
}